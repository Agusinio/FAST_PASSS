#!/bin/bash
# rename_modules.sh — Renomenament de mòduls FASTPASS
# Executa des de Terminal: bash /Volumes/PYTHON/FAST_PASSS_Desarrollo/rename_modules.sh

set -e
BASE="/Volumes/PYTHON/FAST_PASSS_Desarrollo"

echo "── JSX modules ──"
cd "$BASE/jsx/modules"
mv "1_System.jsx"      "10_Sistema.jsx"
mv "2_IO.jsx"          "12_Arxiu.jsx"
mv "3_Project.jsx"     "20_Projecte.jsx"
mv "5_Tracks.jsx"      "31_Pistes.jsx"
mv "6_Clips.jsx"       "32_Segments.jsx"
mv "7_KF.jsx"          "33_Animacio.jsx"
mv "9_Render.jsx"      "34_Exportacio.jsx"
mv "11_Context.jsx"    "11_Entorn.jsx"
mv "12_Diagnostic.jsx" "19_Diagnosi.jsx"
mv "13_Timeline.jsx"   "30_Cronologia.jsx"
echo "  ✅ JSX fet"

echo "── JS Core ──"
cd "$BASE/js/core"
mv "utils.js"            "10_Eines.js"
mv "config.js"           "11_Configuracio.js"
mv "state.js"            "12_Estat.js"
mv "project_registry.js" "13_Registre.js"
mv "4_Context.js"        "14_Sintesi.js"
echo "  ✅ Core fet"

echo "── JS Inspectors ──"
cd "$BASE/js/inspectors"
mv "3_Session.js"      "20_Sessio.js"
mv "2_App.js"          "21_Aplicacio.js"
mv "1_SourceAssets.js" "22_Escaneig_ext.js"
echo "  ✅ Inspectors fet"

echo "── JS Logic ──"
cd "$BASE/js/logic"
mv "Scanner.js"           "22_Escaneig_int.js"
mv "3_Project_Logic.js"   "36_Projecte.js"
mv "5_Tracks_Logic.js"    "31_Pistes.js"
mv "6_Clips_Logic.js"     "32_Segments.js"
mv "7_KF_Logic.js"        "33_Animacio.js"
mv "9_Render_Logic.js"    "34_Exportacio.js"
mv "10_Srt_Logic.js"      "35_Subtitols.js"
mv "13_Parse.js"          "23_Analisi.js"
mv "14_Assembly_Logic.js" "37_Muntatge.js"
echo "  ✅ Logic fet"

echo "── JS Workflows ──"
cd "$BASE/js/workflows"
mv "flow_mainButton.js" "flux_principal.js"
mv "flow_cut.js"        "flux_tall.js"
mv "flow_assembly.js"   "flux_muntatge.js"
mv "flow_retols.js"     "flux_retols.js"
mv "flow_srt.js"        "flux_subtitols.js"
mv "flow_KF.js"         "flux_animacio.js"
mv "flow_render.js"     "flux_exportacio.js"
echo "  ✅ Workflows fet"

echo "── Fusió Scanner (22_Escaneig.js) ──"
cd "$BASE/js/logic"
cat "22_Escaneig_int.js" > "22_Escaneig.js"
echo "" >> "22_Escaneig.js"
echo "// ─── SourceAssets (Inspector extern) ───────────────" >> "22_Escaneig.js"
cat "$BASE/js/inspectors/22_Escaneig_ext.js" >> "22_Escaneig.js"
rm "22_Escaneig_int.js"
rm "$BASE/js/inspectors/22_Escaneig_ext.js"
echo "  ✅ 22_Escaneig.js fusionat"

echo ""
echo "✅ Tots els renomenaments completats."
